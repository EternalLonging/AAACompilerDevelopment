#pragma once
#include "minic/interface.hpp"

namespace minic {

// 将源码分成单词，返回单词表和词法诊断；filename 用于记录来源位置。
//
// ----------------------------------------------------------------------------
// 下面是给组员看的白话说明（接口本身没变）：
//
// 作用：把一段"源码原文"切成一个个"单词"（Token），并收集这一阶段的报错。
//
// 参数：
//   source   要分析的源码，就是一大段字符串，例如 "int a; a = 1;"。
//   filename 这段源码来自哪个文件，只写进报错信息用于定位，默认叫 "<input>"。
//
// 返回 LexResult，里面有两部分：
//   tokens       切出来的单词列表；最后一个固定是 END_OF_FILE（表示输入结束）。
//   diagnostics  词法阶段的报错列表；遇到非法字符时错误写在这里，
//                每条都带"行号、列号、源码位置"。
//
// 一句话理解：输入一串字符，输出一串带"类型/原文/位置"的小卡片 + 一堆报错。
// ----------------------------------------------------------------------------
LexResult lex(const std::string& source,
              const std::string& filename = "<input>");

}
